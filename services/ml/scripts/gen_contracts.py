"""Generate Pydantic v2 models from the contracts JSON Schema bundle.

Run through `pnpm contracts:gen` (or `pnpm contracts:check`, which passes --schema/--output
pointing at a temp dir). Source: packages/contracts/schema/contracts.json, emitted from Zod.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ML_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = ML_ROOT.parents[1]
DEFAULT_SCHEMA = REPO_ROOT / "packages/contracts/schema/contracts.json"
DEFAULT_OUTPUT = ML_ROOT / "packages/splitune_ml_core/src/splitune_ml_core/contracts/_generated.py"
HEADER = (
    "# Generated by `pnpm contracts:gen` from packages/contracts/schema/contracts.json.\n"
    "# Do not edit: change the Zod schemas in packages/contracts/src and regenerate."
)

CODEGEN_ARGS = [
    "--input-file-type=jsonschema",
    "--output-model-type=pydantic_v2.BaseModel",
    "--target-python-version=3.12",
    "--skip-root-model",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-type-alias",
    "--enum-field-as-literal=all",
    "--use-double-quotes",
    "--disable-timestamp",
    "--formatters=builtin",
    # Mirror Zod: no coercion ("1.5" is not a number, 1 is not a bool).
    "--strict-types",
    "str",
    "int",
    "float",
    "bool",
    # Keep these as strings validated by Zod's exact regex instead of Pydantic's laxer parsers
    # (e.g. datetime accepting unix timestamps), so both languages accept the same documents.
    "--type-mappings",
    "string+date-time=string",
    "string+uuid=string",
    "string+uri=string",
    "string+email=string",
]


def run(*args: str | Path, stdin: str | None = None) -> str:
    return subprocess.run(
        [sys.executable, "-m", *map(str, args)],
        check=True,
        cwd=ML_ROOT,
        input=stdin,
        stdout=subprocess.PIPE,
        text=True,
    ).stdout


def generate(schema: Path, output: Path) -> None:
    version = json.loads(schema.read_text())["x-schema-version"]
    with tempfile.TemporaryDirectory() as tmp:
        generated = Path(tmp) / "_generated.py"
        run(
            "datamodel_code_generator",
            f"--input={schema}",
            f"--output={generated}",
            f"--custom-file-header={HEADER}",
            *CODEGEN_ARGS,
        )
        code = f'{generated.read_text()}\n\nSCHEMA_VERSION = "{version}"\n'
    # Lint and format as if the code sat at its committed path, so the project's ruff settings
    # (including per-file ignores) apply wherever the output goes.
    as_path = f"--stdin-filename={DEFAULT_OUTPUT}"
    code = run("ruff", "check", "--fix", "--quiet", as_path, "-", stdin=code)
    code = run("ruff", "format", "--quiet", as_path, "-", stdin=code)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(code)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    generate(args.schema.resolve(), args.output.resolve())


if __name__ == "__main__":
    main()
